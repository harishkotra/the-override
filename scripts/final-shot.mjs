import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome' })
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } })
await p.goto('http://127.0.0.1:8791/', { waitUntil: 'domcontentloaded' })
await p.waitForSelector('header h1')
await p.getByRole('button', { name: /Compile extension/ }).click({ timeout: 150000 })
await p.waitForSelector('.verdict.pass, .verdict.fail', { timeout: 240000 })
await p.waitForTimeout(800)
const terms = await p.locator('.term pre').allInnerTexts()
console.log('BLOCK 3 (info):\n' + (terms[2] || '').trim())
console.log('\nblocks:', terms.length, '| verdict:', (await p.locator('.verdict .big').innerText()))
console.log('cols:', await p.evaluate(() => [...document.querySelectorAll('.grid > .panel')].map((x) => Math.round(x.getBoundingClientRect().width))))
await p.screenshot({ path: 'screens/ui-fixed.png', fullPage: true })
await b.close()
